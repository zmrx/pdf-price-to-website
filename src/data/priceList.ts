/** Ячейка таблицы с возможным объединением по столбцам/строкам */
export interface PriceCell {
  text: string
  /** Объединение ячеек по горизонтали (атрибут colspan) */
  colspan?: number
  /** Объединение ячеек по вертикали (атрибут rowspan) */
  rowspan?: number
}

/** Строка таблицы; строка — сокращение для { text: строка } */
export interface PriceRow {
  cells: (string | PriceCell)[]
}

/** Группа строк таблицы с полноширинным заголовком */
export interface PriceGroup {
  /** Заголовок группы (полноширинная строка) */
  title?: string
  /** Примечание под заголовком группы (полноширинная строка) */
  note?: string
  rows: PriceRow[]
}

/** Таблица прайс-листа целиком */
export interface PriceTable {
  /** Идентификатор для URL: /table/:id */
  id: string
  /** Название таблицы (как в PDF) */
  title: string
  /** Заголовки колонок */
  columns: string[]
  /** Индексы колонок (0-based) с числовыми значениями — выравнивание вправо */
  numericColumns: number[]
  groups: PriceGroup[]
  /** Сноска под таблицей */
  footnote?: string
}

/** Общие реквизиты прайс-листа (шапка и подвал страницы PDF) */
export interface PriceListMeta {
  brand: string
  subtitle: string
  warning: string
  warningUrl: string
  warningUrlLabel: string
  footerNote: string
}

